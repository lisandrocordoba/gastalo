import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import XLSX from 'xlsx';
import { mapWalletRows } from './wallet-mapper.mjs';

function parseArgs(argv) {
  const args = {
    file: 'imports/report_2026-06-30_215634.xls',
    out: '.wrangler/wallet-import.sql',
    replace: false,
    applyLocal: false,
    applyRemote: false,
    confirmRemote: false,
  };

  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--file' && argv[i + 1]) args.file = argv[++i];
    else if (a === '--out' && argv[i + 1]) args.out = argv[++i];
    else if (a === '--replace') args.replace = true;
    else if (a === '--apply-local') args.applyLocal = true;
    else if (a === '--apply-remote') args.applyRemote = true;
    else if (a === '--confirm-remote') args.confirmRemote = true;
  }
  return args;
}

function sqlVal(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

function parseExcelDate(rawDate) {
  if (typeof rawDate === 'number' && rawDate > 0) {
    const parsed = XLSX.SSF.parse_date_code(rawDate);
    if (parsed) {
      const y = String(parsed.y).padStart(4, '0');
      const m = String(parsed.m).padStart(2, '0');
      const d = String(parsed.d).padStart(2, '0');
      const hh = String(parsed.H ?? 0).padStart(2, '0');
      const mm = String(parsed.M ?? 0).padStart(2, '0');
      const ss = String(Math.floor(parsed.S ?? 0)).padStart(2, '0');
      const dateIso = `${y}-${m}-${d}`;
      const isoTimestamp = `${dateIso}T${hh}:${mm}:${ss}.000Z`;
      return { dateIso, isoTimestamp, timestampMs: Date.parse(isoTimestamp) };
    }
  }
  const d = new Date(String(rawDate));
  if (!Number.isNaN(d.getTime())) {
    const iso = d.toISOString();
    return { dateIso: iso.slice(0, 10), isoTimestamp: iso, timestampMs: d.getTime() };
  }
  throw new Error(`Fecha inválida en Excel: ${rawDate}`);
}

function buildSql(transactions, replace) {
  const lines = ['-- Generated by scripts/import-wallet.mjs'];
  if (replace) {
    lines.push("DELETE FROM transactions WHERE source = 'wallet_import';");
  }

  const chunkSize = 100;
  for (let i = 0; i < transactions.length; i += chunkSize) {
    const chunk = transactions.slice(i, i + chunkSize);
    const values = chunk
      .map(
        (tx) =>
          `(${sqlVal(tx.id)}, ${sqlVal(tx.type)}, ${sqlVal(tx.amount)}, ${sqlVal(tx.currency)}, ${sqlVal(tx.account_id)}, ${sqlVal(tx.to_account_id)}, ${sqlVal(tx.category_id)}, ${sqlVal(tx.description)}, ${sqlVal(tx.occurred_at)}, ${sqlVal(tx.source)}, ${sqlVal(tx.raw_input)}, NULL, ${sqlVal(tx.installments_total)}, ${sqlVal(tx.first_installment_month)}, ${sqlVal(tx.third_party_name)}, ${sqlVal(tx.linked_group_id)}, ${sqlVal(tx.created_at)})`
      )
      .join(',\n');

    lines.push(
      `INSERT OR REPLACE INTO transactions (id, type, amount, currency, account_id, to_account_id, category_id, description, occurred_at, source, raw_input, telegram_message_id, installments_total, first_installment_month, third_party_name, linked_group_id, created_at) VALUES\n${values};`
    );
  }

  const allTags = new Set();
  const tagLinks = [];
  for (const tx of transactions) {
    for (const tag of tx.tags) {
      allTags.add(tag);
      tagLinks.push([tx.id, tag]);
    }
  }

  if (allTags.size > 0) {
    const tagValues = Array.from(allTags)
      .sort()
      .map((t) => `(${sqlVal(t)}, ${sqlVal(t)}, '#71717a')`)
      .join(', ');
    lines.push(`INSERT OR IGNORE INTO tags (id, name, color) VALUES ${tagValues};`);
  }

  for (let i = 0; i < tagLinks.length; i += chunkSize) {
    const chunk = tagLinks.slice(i, i + chunkSize);
    const values = chunk.map(([txId, tagId]) => `(${sqlVal(txId)}, ${sqlVal(tagId)})`).join(', ');
    lines.push(`INSERT OR IGNORE INTO transaction_tags (transaction_id, tag_id) VALUES ${values};`);
  }

  return lines.join('\n\n') + '\n';
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.applyRemote && !args.confirmRemote) {
    console.error('Error: --apply-remote requiere --confirm-remote explícitamente.');
    process.exit(1);
  }

  const absFile = path.resolve(args.file);
  if (!fs.existsSync(absFile)) {
    console.error(`Archivo no encontrado: ${absFile}`);
    process.exit(1);
  }

  const wb = XLSX.readFile(absFile, { cellDates: false });
  const sheetName = wb.SheetNames.includes('Registros') ? 'Registros' : wb.SheetNames[0];
  const rawSheetRows = XLSX.utils.sheet_to_json(wb.Sheets[sheetName], { defval: '' });

  const normalizedRows = rawSheetRows.map((r) => {
    const dt = parseExcelDate(r.date);
    return {
      account: r.account,
      category: r.category,
      currency: r.currency,
      amount: Number(r.amount || 0),
      type: r.type,
      note: r.note,
      labels: r.labels,
      payee: r.payee,
      transfer: Number(r.transfer || 0),
      ...dt,
    };
  });

  const { transactions, stats, balanceAudit } = mapWalletRows(normalizedRows);

  const byType = {};
  const byCat = {};
  const byTag = {};
  let withInstallments = 0;

  for (const tx of transactions) {
    byType[tx.type] = (byType[tx.type] ?? 0) + 1;
    if (tx.category_id) byCat[tx.category_id] = (byCat[tx.category_id] ?? 0) + 1;
    for (const tag of tx.tags) byTag[tag] = (byTag[tag] ?? 0) + 1;
    if (tx.installments_total) withInstallments++;
  }

  console.log('\n=== Resumen Importación Wallet ===');
  console.log(`Archivo: ${args.file} (hoja "${sheetName}")`);
  console.log(`Filas Excel: ${stats.raw_rows} -> Registros v2: ${stats.mapped_transactions}`);
  console.log(`Pares TRANSFER unificados: ${stats.paired_transfers} | Huérfanos a adjustment: ${stats.orphan_transfers_as_adjustments}`);
  console.log(`Con cuotas detectadas: ${withInstallments}`);
  console.log('Por tipo:', byType);
  console.log('Por etiqueta:', byTag);
  console.log(
    'Top categorías:',
    Object.entries(byCat)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 10)
  );
  console.log('\n=== Auditoría de Saldos (Excel vs. v2) ===');
  console.table(balanceAudit);

  const hasDiff = balanceAudit.some((b) => Math.abs(b.diff) >= 0.01);
  if (hasDiff) {
    console.error('ABORTADO: Se detectó diferencia de saldo entre el Excel y el mapeo v2.');
    process.exit(1);
  }

  const outPath = path.resolve(args.out);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, buildSql(transactions, args.replace), 'utf8');
  console.log(`SQL generado en: ${outPath}`);

  if (args.applyLocal) {
    console.log('\nAplicando en D1 local...');
    execFileSync(
      'npx',
      ['wrangler', 'd1', 'execute', 'wallet-db', '--local', '--file', outPath],
      { stdio: 'inherit', shell: true }
    );
  }

  if (args.applyRemote && args.confirmRemote) {
    console.log('\nAplicando en D1 remoto...');
    execFileSync(
      'npx',
      ['wrangler', 'd1', 'execute', 'wallet-db', '--remote', '--file', outPath],
      { stdio: 'inherit', shell: true }
    );
  }
}

main();
